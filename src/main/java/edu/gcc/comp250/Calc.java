package edu.gcc.comp250;

public class Calc {
    /**
     * @param a
     * @param b
     * @return
     */
    public int add(int a, int b) {
        return a + b;
    }

    /**
     * @param a
     * @param b
     * @return
     */
    public int divide(int a, int b) {
        return a / b;
    }
}
